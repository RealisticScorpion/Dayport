// Generates src/styles/fonts.css from the bundled @fontsource packages.
// Only WOFF2 sources are kept: Chrome 120+ supports WOFF2, and dropping the
// WOFF fallbacks halves the packaged extension size. Unicode-range splitting
// is preserved, so the browser loads only the CJK chunks a page actually uses.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "src/styles/fonts.css");

const sources = [
  "node_modules/@fontsource/ibm-plex-sans/latin-400.css",
  "node_modules/@fontsource/ibm-plex-sans/latin-500.css",
  "node_modules/@fontsource/ibm-plex-sans/latin-600.css",
  "node_modules/@fontsource/noto-serif-sc/400.css",
];

const chunks = sources.map((source) => {
  const cssDir = dirname(join(root, source));
  const css = readFileSync(join(root, source), "utf8");
  return css
    .replace(/,\s*url\([^)]+\.woff\) format\('woff'\)/g, "")
    .replace(/url\(\.\/([^)]+)\)/g, (_, file) => {
      const target = relative(dirname(outFile), join(cssDir, file));
      return `url(${target})`;
    });
});

writeFileSync(
  outFile,
  `/* Generated by scripts/generate-fonts-css.mjs. Do not edit by hand. */\n${chunks.join("\n")}\n`,
);
console.log(`Wrote ${relative(root, outFile)}`);
