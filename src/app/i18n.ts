export type MessageKey = keyof Messages;
export type Locale = "en" | "zh-CN";
export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function resolveLocale(language: Settings["language"]): Locale {
  if (language !== "auto") return language;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function makeTranslate(locale: Locale): Translate {
  const messages = locale === "zh-CN" ? zh : en;
  return (key, vars) =>
    messages[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`));
}

export const I18nContext = createContext<{ t: Translate; locale: Locale }>({
  t: makeTranslate("en"),
  locale: "en",
});

export const useI18n = () => useContext(I18nContext);

/** "14:05" for today, otherwise a short date such as "Nov 3" or "11月3日". */
export function formatSavedAt(time: number, locale: Locale, now = new Date()): string {
  const date = new Date(time);
  if (date.toDateString() === now.toDateString()) {
    return new Intl.DateTimeFormat(locale, { hour: "2-digit", minute: "2-digit" }).format(date);
  }
  return new Intl.DateTimeFormat(locale, {
    month: "short",
    day: "numeric",
    ...(date.getFullYear() === now.getFullYear() ? {} : { year: "numeric" }),
  }).format(date);
}
